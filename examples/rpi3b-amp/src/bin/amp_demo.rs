#![no_std]
#![no_main]
//! Rivet on one core of a Raspberry Pi 3 while Linux runs on the rest.
//!
//! Linux boots normally on cores 0-2, told by `maxcpus=3` not to take the
//! fourth and by `mem=` not to touch the memory this image lives in. A
//! loader on the Linux side copies this image into that memory and
//! releases core 3 through the firmware's spin table, exactly as the
//! bare-metal `core3_demo` does, except that the releasing core is now
//! running an operating system.
//!
//! Two things differ from every earlier image here, and both come from no
//! longer being alone on the machine:
//!
//! - **Entry.** There is no core guard and no boot-time UART checkpoint.
//!   Whichever core arrives is the one rivet was handed, and the serial
//!   line belongs to Linux. See the `amp` feature in `rivet-bsp-rpi3b`.
//! - **Console.** Output goes to a ring in shared memory that Linux reads,
//!   rather than to the UART. There is only one UART on the header, and
//!   interleaving two consoles onto it helps nobody.
//!
//! Everything else is the ordinary port: drop to EL1, install the
//! identity map, run the kernel.

use core::fmt::Write;

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::{boot::Diag, drop_to_el1, kernel, mmu, shmem, smp};

/// Where this image is linked and where the loader must place it. Kept in
/// step with `RIVET_RPI3B_LOAD_ADDR` in this package's cargo config.
const EXPECTED_BASE: u64 = 0x3000_0000;

macro_rules! sysreg {
    ($name:literal) => {{
        let v: u64;
        // SAFETY: reading a system register has no side effects.
        unsafe {
            core::arch::asm!(concat!("mrs {}, ", $name), out(reg) v,
                             options(nomem, nostack, preserves_flags))
        };
        v
    }};
}

fn start_addr() -> u64 {
    let v: u64;
    // SAFETY: ADR only computes a PC-relative address.
    unsafe { core::arch::asm!("adr {}, _start", out(reg) v, options(nomem, nostack)) };
    v
}

#[no_mangle]
pub extern "C" fn rust_main(_x0: u64) -> ! {
    // The shared ring has to exist before anything can be reported,
    // because it is the only way out of here.
    // SAFETY: the window is Device-mapped by the identity map below, and
    // is untranslated until then, so this write lands either way.
    unsafe { shmem::init() };
    let mut d = Diag;

    let _ = write!(
        d,
        "\n\
         ==== rivet: core {} alongside Linux ====\n\
         [rivet] MPIDR_EL1   {:#018x}\n\
         [rivet] CurrentEL   {}\n\
         [rivet] CNTFRQ_EL0  {} Hz\n\
         [rivet] _start at   {:#018x}  (linked for {EXPECTED_BASE:#x})\n",
        smp::current_core(),
        sysreg!("mpidr_el1"),
        sysreg!("CurrentEL") >> 2,
        sysreg!("cntfrq_el0"),
        start_addr(),
    );

    // A mismatch here means the loader put the image somewhere other than
    // where it was linked, which would make every absolute address in it
    // wrong. Worth catching before anything else runs.
    if start_addr() != EXPECTED_BASE {
        let _ = writeln!(d, "!! LOAD_ADDR mismatch, refusing to continue");
        park();
    }

    // SAFETY: called once on this core, from EL2, with a valid stack.
    unsafe { drop_to_el1() };
    // SAFETY: at EL1 with translation off. Nothing else built these
    // tables: Linux has its own, in memory this image never touches.
    unsafe { mmu::enable_el1() };

    let _ = write!(
        d,
        "[rivet] dropped to EL{}, MMU on (SCTLR_EL1 {:#018x})\n\
         [rivet] shared ring at {:#x}, mapped Device so Linux sees it uncached\n",
        sysreg!("CurrentEL") >> 2,
        sysreg!("sctlr_el1"),
        shmem::SHARED_BASE,
    );

    {
        use core::sync::atomic::{AtomicUsize, Ordering};
        static N: AtomicUsize = AtomicUsize::new(0);
        let a = N.fetch_add(1, Ordering::SeqCst);
        let ok = a == 0 && N.load(Ordering::SeqCst) == 1;
        let _ = writeln!(d, "[rivet] atomics     {}", if ok { "OK" } else { "WRONG" });
        if !ok {
            park();
        }
    }

    // Send the kernel's console to the ring too, and keep it off the
    // UART: `__rivet_board_init` would otherwise re-mux GPIO14/15 and
    // pull the serial console out from under Linux mid-sentence.
    // SAFETY: the ring is initialised and the window is mapped.
    unsafe { kernel::use_shared_console() };
    let _ = writeln!(d, "[rivet] console redirected to shared memory");

    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

fn park() -> ! {
    loop {
        // SAFETY: WFE is side-effect free.
        unsafe { core::arch::asm!("wfe", options(nomem, nostack)) };
    }
}

// ── The kernel ────────────────────────────────────────────────────

use core::sync::atomic::{AtomicU32, Ordering};

static TICKS: AtomicU32 = AtomicU32::new(0);
/// Worst deviation from the nominal period since warm-up, in microseconds.
static WORST_US: AtomicU32 = AtomicU32::new(0);
/// Worst deviation within the current reporting window.
static WINDOW_US: AtomicU32 = AtomicU32::new(0);
/// Wakeups that landed more than half a tick from nominal.
static LATE: AtomicU32 = AtomicU32::new(0);

const PERIOD_US: u64 = 10_000;
/// Iterations to discard before measuring.
///
/// The first wakeup has to align onto the tick grid, so it carries up to
/// one full tick period of phase error that says nothing about how
/// steadily the task runs afterwards. Folding that into a lifetime
/// maximum pins the figure at ~1000 us forever and hides the real
/// behaviour, which is exactly what the first version of this did.
const WARMUP: u32 = 20;

/// A periodic task, which is the whole point of the arrangement: it wants
/// to wake on time regardless of what Linux is doing on the other cores.
fn periodic(_: &'static ()) -> ! {
    let mut next = rivet::port::board::now_us() + PERIOD_US;
    let mut last = rivet::port::board::now_us();
    let mut n: u32 = 0;
    loop {
        rivet::preempt::sleep_until(next);
        let now = rivet::port::board::now_us();
        let gap = now - last;
        last = now;
        next += PERIOD_US;
        n += 1;

        if n > WARMUP {
            let err = gap.abs_diff(PERIOD_US) as u32;
            WORST_US.fetch_max(err, Ordering::Relaxed);
            WINDOW_US.fetch_max(err, Ordering::Relaxed);
            // Half a tick is the point past which the wakeup missed its
            // grid slot rather than merely landing on it imprecisely.
            if err > 500 {
                LATE.fetch_add(1, Ordering::Relaxed);
            }
        }
        TICKS.fetch_add(1, Ordering::Relaxed);
    }
}

fn reporter(_: &'static ()) -> ! {
    let mut round = 0u32;
    loop {
        rivet::preempt::sleep_ms(1000);
        round += 1;
        let t = TICKS.load(Ordering::Relaxed);
        let worst = WORST_US.load(Ordering::Relaxed);
        let window = WINDOW_US.swap(0, Ordering::Relaxed);
        let late = LATE.load(Ordering::Relaxed);
        rivet::console::write_str("[rivet] t=");
        print_dec(round as usize);
        rivet::console::write_str("s wakeups=");
        print_dec(t as usize);
        rivet::console::write_str(" jitter_us last1s=");
        print_dec(window as usize);
        rivet::console::write_str(" worst=");
        print_dec(worst as usize);
        rivet::console::write_str(" late=");
        print_dec(late as usize);
        rivet::console::write_str("\n");
    }
}

fn print_dec(mut v: usize) {
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

#[rivet::main]
fn main() -> ! {
    rivet::console::write_str("[kernel] rivet started alongside Linux\n");
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 2, entry = periodic, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = reporter, arg = ());
    rivet::run();
}
