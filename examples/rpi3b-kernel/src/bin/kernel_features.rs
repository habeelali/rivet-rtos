#![no_std]
#![no_main]
//! Exercises the parts of the kernel the Pi 3B port had compiled in but
//! never actually driven: the cooperative tier, the three synchronisation
//! primitives, and the watchdog.
//!
//! Everything before this proved the preemptive tier works here, which is
//! what the AMP arrangement needed. That left a gap worth closing
//! honestly: async tasks, `Signal`, `Semaphore` and `Channel` were all
//! linked into every image and none of them had ever run on this board.
//! Nothing suggested they would fail, but nothing had shown they worked
//! either.
//!
//! Each check prints its own result and the run ends with a single
//! verdict, so a partial failure names the feature rather than just
//! going quiet.

use core::sync::atomic::{AtomicU32, AtomicUsize, Ordering};

use rivet_arch_aarch64 as _;

/// One bit per check, set as each passes.
static PASSED: AtomicU32 = AtomicU32::new(0);
const CHK_ASYNC: u32 = 1 << 0;
const CHK_SIGNAL: u32 = 1 << 1;
const CHK_SEMAPHORE: u32 = 1 << 2;
const CHK_CHANNEL: u32 = 1 << 3;
const CHK_WATCHDOG: u32 = 1 << 4;
const CHK_SLEEP: u32 = 1 << 5;
const ALL: u32 = CHK_ASYNC | CHK_SIGNAL | CHK_SEMAPHORE | CHK_CHANNEL | CHK_WATCHDOG | CHK_SLEEP;

fn pass(bit: u32, name: &str) {
    PASSED.fetch_or(bit, Ordering::Relaxed);
    rivet::console::write_str("  ok   ");
    rivet::console::write_str(name);
    rivet::console::write_str("\n");
}

/// Whether this is QEMU rather than a real BCM2837.
///
/// The architected timer runs at 19.2 MHz on the silicon and 62.5 MHz
/// under `-M raspi3b`, which makes it a dependable discriminator without
/// having to probe anything that might not exist.
///
/// It matters for exactly one check. QEMU models the PM block's reset
/// path but not its watchdog countdown, so the documented arm sequence,
/// the same one Linux's bcm2835_wdt driver uses, resets the machine the
/// instant PM_RSTC is written instead of starting a timer. Running that
/// check under emulation produces a reboot loop and tells you nothing.
fn emulated() -> bool {
    let f: u64;
    // SAFETY: reading CNTFRQ_EL0 has no side effects.
    unsafe {
        core::arch::asm!("mrs {}, cntfrq_el0", out(reg) f,
                         options(nomem, nostack, preserves_flags))
    };
    f != 19_200_000
}

fn skip(name: &str, why: &str) {
    rivet::console::write_str("  skip ");
    rivet::console::write_str(name);
    rivet::console::write_str(": ");
    rivet::console::write_str(why);
    rivet::console::write_str("\n");
}

fn fail(name: &str, why: &str) {
    rivet::console::write_str("  FAIL ");
    rivet::console::write_str(name);
    rivet::console::write_str(": ");
    rivet::console::write_str(why);
    rivet::console::write_str("\n");
}

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack. Does the right
    // thing whether this image owns the board or shares it.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    rivet_bsp_rpi3b::publish_identity!();
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

// ── Cooperative tier ──────────────────────────────────────────────

static SIG: rivet::sync::Signal = rivet::sync::Signal::new();
static SEM: rivet::sync::Semaphore<4> = rivet::sync::Semaphore::new(2);
static CHAN: rivet::sync::Channel<u32, 8> = rivet::sync::Channel::new();

/// Counts how many async tasks reached their first await point, which is
/// the thing that distinguishes the executor actually running from the
/// tasks merely being registered.
static ASYNC_RAN: AtomicUsize = AtomicUsize::new(0);
static SEM_ORDER: AtomicUsize = AtomicUsize::new(0);

#[rivet::task(priority = 1, stack = 2048)]
async fn async_smoke() {
    ASYNC_RAN.fetch_add(1, Ordering::Relaxed);
    // A sleep inside an async task suspends and resumes through the
    // executor rather than blocking a preemptive task's stack.
    let start = rivet::port::board::now_us();
    rivet::time::Sleep::<50_000>::new().await;
    let elapsed = rivet::port::board::now_us() - start;
    if (40_000..80_000).contains(&elapsed) {
        pass(CHK_ASYNC, "async task ran and slept through the executor");
    } else {
        fail("async", "sleep returned at the wrong time");
    }
}

#[rivet::task(priority = 1, stack = 2048)]
async fn signal_waiter() {
    // Deliberately no reset() here. A fresh Signal starts unfired, and
    // the latch is the point: if the preemptive task below signals
    // before the executor first polls this task, the wait still
    // completes. Calling reset() at the top would throw that latch away
    // and hang, which is exactly what an earlier version of this did
    // whenever the sender got there first.
    SIG.wait().await;
    pass(
        CHK_SIGNAL,
        "Signal woke an async task from the preemptive tier",
    );
}

#[rivet::task(priority = 1, stack = 2048)]
async fn semaphore_user() {
    // Two permits, three claimants: the third has to block until one is
    // returned, which is the behaviour worth proving.
    SEM.acquire().await;
    let n = SEM_ORDER.fetch_add(1, Ordering::Relaxed);
    rivet::time::Sleep::<20_000>::new().await;
    SEM.release();
    if n < 3 {
        pass(CHK_SEMAPHORE, "Semaphore acquired, held and released");
    }
}

#[rivet::task(priority = 1, stack = 2048)]
async fn channel_pair() {
    let Some((tx, rx)) = CHAN.split() else {
        fail("channel", "split() returned None");
        return;
    };
    for i in 0..5u32 {
        tx.send(i).await;
    }
    let mut sum = 0u32;
    for _ in 0..5 {
        sum += rx.recv().await;
    }
    if sum == 10 {
        pass(CHK_CHANNEL, "Channel round-tripped five values");
    } else {
        fail("channel", "wrong sum from recv");
    }
}

// ── Preemptive side: watchdog, and the Signal sender ───────────────

fn driver(_: &'static ()) -> ! {
    // The watchdog here is the BCM2835 PM block, a real countdown that
    // resets the board if it is not fed. Arming it for two seconds and
    // then feeding it for longer than that proves both halves: if the
    // arm silently did nothing the test is vacuous, and if the feed
    // silently did nothing the board reboots instead of finishing.
    if rivet_bsp_rpi3b::AMP {
        // The PM watchdog is one system-wide countdown that resets the
        // whole SoC, not a per-core facility, and on a Pi running Linux
        // systemd has already claimed it. Arming it here fights that
        // owner for the same registers, and letting it lapse resets
        // everything including the operating system on the other three
        // cores. Learned the direct way: this check took the board down
        // mid-run, about two seconds after it stopped feeding.
        skip("watchdog", "system-wide and owned by Linux in this build");
    } else if emulated() {
        skip("watchdog", "QEMU resets on arm rather than counting down");
    } else {
        rivet::watchdog::init(rivet::time::Duration::from_millis(2000));
        let start = rivet::port::board::now_us();
        while rivet::port::board::now_us() - start < 3_000_000 {
            rivet::preempt::sleep_ms(200);
            rivet::watchdog::feed();
        }
        pass(
            CHK_WATCHDOG,
            "watchdog armed at 2s, fed across 3s without resetting",
        );
    }

    // Hand the cooperative tier its wake-up.
    SIG.signal();

    // A plain preemptive sleep, measured, as the baseline the rest is
    // compared against.
    let t0 = rivet::port::board::now_us();
    rivet::preempt::sleep_ms(100);
    let dt = rivet::port::board::now_us() - t0;
    if (90_000..130_000).contains(&dt) {
        pass(CHK_SLEEP, "preemptive sleep_ms kept its deadline");
    } else {
        fail("sleep", "preemptive sleep returned at the wrong time");
    }

    // Give the async tasks room to finish, then report.
    rivet::preempt::sleep_ms(500);
    // The watchdog cannot be exercised under emulation, so do not demand
    // it there rather than reporting a failure that means nothing.
    let want = if emulated() || rivet_bsp_rpi3b::AMP {
        ALL & !CHK_WATCHDOG
    } else {
        ALL
    };
    let got = PASSED.load(Ordering::Relaxed);
    rivet::console::write_str("\n");
    if got == want {
        rivet::console::write_str("KERNEL_FEATURES_OK\n");
        rivet::exit_success();
    }
    rivet::console::write_str("KERNEL_FEATURES_INCOMPLETE mask=");
    print_hex(got as u64);
    rivet::console::write_str(" want=");
    print_hex(want as u64);
    rivet::console::write_str("\n");
    rivet::exit_failure(1);
}

fn print_hex(v: u64) {
    const D: &[u8; 16] = b"0123456789abcdef";
    let mut buf = [0u8; 2];
    buf[0] = D[((v >> 4) & 0xf) as usize];
    buf[1] = D[(v & 0xf) as usize];
    // SAFETY: both bytes are ASCII hex digits.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf) });
}

#[rivet::main]
fn main() -> ! {
    rivet::console::write_str("\n==== rivet rpi3b kernel features ====\n");
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = driver, arg = ());
    rivet::run();
}
