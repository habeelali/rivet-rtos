#![no_std]
#![no_main]
//! A two-way channel between Linux and rivet.
//!
//! Everything before this was a reporting pipe: rivet talked, Linux
//! listened. This closes the loop. Linux writes a command into a ring and
//! rings rivet's mailbox doorbell; rivet is asleep in `WFI` until the
//! interrupt arrives, reads the command, acts on it and answers on the
//! console ring.
//!
//! The doorbell matters more than it might look. A ring on its own only
//! supports polling, and polling a shared window from a real-time core is
//! the wrong shape twice over: it burns the core while idle and still
//! adds latency when busy. The ARM-local mailboxes are the one interrupt
//! source on this SoC that can be aimed at a specific core, so they are
//! what makes an idle-until-asked design possible here at all.
//!
//! Commands, one per line:
//!
//! ```text
//! ping          answer pong
//! stats         report uptime, doorbells taken, period
//! period <ms>   change the periodic task's period
//! quit          stop
//! ```
//!
//! From Linux:
//!
//! ```text
//! sudo rivet-amp send ping
//! sudo rivet-amp send "period 25"
//! sudo rivet-amp console
//! ```

use core::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, Ordering};

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::{kernel, shmem};

static PERIOD_MS: AtomicU32 = AtomicU32::new(10);
static WAKEUPS: AtomicU64 = AtomicU64::new(0);
static QUIT: AtomicBool = AtomicBool::new(false);

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

fn w(s: &str) {
    rivet::console::write_str(s);
}

fn print_dec(mut v: u64) {
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

/// Parse a decimal number from the tail of a command.
fn parse_u32(s: &[u8]) -> Option<u32> {
    let mut v: u32 = 0;
    let mut any = false;
    for &c in s {
        if c.is_ascii_digit() {
            v = v.checked_mul(10)?.checked_add((c - b'0') as u32)?;
            any = true;
        } else if any {
            break;
        }
    }
    any.then_some(v)
}

fn handle(cmd: &[u8]) {
    // Trim trailing whitespace and newlines the sender may have included.
    let mut end = cmd.len();
    while end > 0 && (cmd[end - 1] == b'\n' || cmd[end - 1] == b'\r' || cmd[end - 1] == b' ') {
        end -= 1;
    }
    let cmd = &cmd[..end];
    if cmd.is_empty() {
        return;
    }

    if cmd.starts_with(b"ping") {
        w("[rivet] pong\n");
    } else if cmd.starts_with(b"stats") {
        w("[rivet] uptime_us=");
        print_dec(rivet::port::board::now_us());
        w(" doorbells=");
        print_dec(kernel::doorbell_count() as u64);
        w(" wakeups=");
        print_dec(WAKEUPS.load(Ordering::Relaxed));
        w(" period_ms=");
        print_dec(PERIOD_MS.load(Ordering::Relaxed) as u64);
        w("\n");
    } else if cmd.starts_with(b"period") {
        match parse_u32(&cmd[6..]) {
            // A period of zero would spin the periodic task flat out, so
            // reject it rather than let a typo saturate the core.
            Some(ms) if (1..=10_000).contains(&ms) => {
                PERIOD_MS.store(ms, Ordering::Relaxed);
                w("[rivet] period now ");
                print_dec(ms as u64);
                w(" ms\n");
            }
            _ => w("[rivet] period needs a value between 1 and 10000\n"),
        }
    } else if cmd.starts_with(b"quit") {
        w("[rivet] stopping\n");
        QUIT.store(true, Ordering::Relaxed);
    } else {
        w("[rivet] unknown command\n");
    }
}

/// Waits on the doorbell, so the core is idle between commands rather
/// than polling the shared window.
#[rivet::task(priority = 2, stack = 4096)]
async fn commands() {
    let mut buf = [0u8; 256];
    loop {
        kernel::DOORBELL.wait().await;
        kernel::DOORBELL.reset();
        loop {
            // SAFETY: the shared window is mapped and the rings are up.
            let n = unsafe { shmem::COMMAND.read_bytes(&mut buf) };
            if n == 0 {
                break;
            }
            // One command per line: a single doorbell may cover several.
            let mut start = 0;
            for i in 0..n {
                if buf[i] == b'\n' {
                    handle(&buf[start..i]);
                    start = i + 1;
                }
            }
            if start < n {
                handle(&buf[start..n]);
            }
        }
    }
}

fn periodic(_: &'static ()) -> ! {
    loop {
        WAKEUPS.fetch_add(1, Ordering::Relaxed);
        rivet::preempt::sleep_ms(PERIOD_MS.load(Ordering::Relaxed) as u64);
    }
}

fn supervisor(_: &'static ()) -> ! {
    // SAFETY: called once, on the core that services the doorbell.
    unsafe { kernel::enable_doorbell() };
    w("\n==== rivet rpi3b channel ====\n");
    w("[rivet] doorbell armed, waiting for commands from Linux\n");
    w("[rivet] try: sudo rivet-amp send ping\n");

    let start = rivet::port::board::now_us();
    loop {
        rivet::preempt::sleep_ms(500);
        if QUIT.load(Ordering::Relaxed) {
            w("\nCHANNEL_DEMO_OK\n");
            rivet::exit_success();
        }
        // Do not sit here forever if nobody is driving it.
        if rivet::port::board::now_us() - start > 120_000_000 {
            w("\nCHANNEL_DEMO_TIMEOUT: no quit received in 120 s\n");
            rivet::exit_failure(1);
        }
    }
}

#[rivet::main]
fn main() -> ! {
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = periodic, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = supervisor, arg = ());
    rivet::run();
}
