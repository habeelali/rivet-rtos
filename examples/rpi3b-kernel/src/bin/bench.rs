#![no_std]
#![no_main]
//! Timing benchmarks for the AArch64 port.
//!
//! Everything is measured with `CNTPCT_EL0`, the architected counter,
//! which runs at 19.2 MHz on this board: one tick is 52.083 ns and the
//! counter is not affected by CPU frequency scaling. Figures are reported
//! in nanoseconds, converted exactly (`ns = ticks * 625 / 12`).
//!
//! Where a number comes from matters as much as the number, so each
//! section says what it actually contains:
//!
//! - **Interrupt latency** is measured against the timer's own comparator
//!   value, which is the exact hardware instant of expiry. It therefore
//!   covers exception entry, the full 272-byte register save and the
//!   board's interrupt demux, with nothing estimated.
//! - **Reschedule round trip** is `SVC` in, save, ask the scheduler,
//!   restore, `ERET` out, with the same task chosen again. It is the cost
//!   of the context-switch machinery without an actual task change.
//! - **Task-to-task switch** adds the change: two tasks handing control
//!   back and forth, measured per switch.
//! - **Periodic jitter** is wall-clock deviation of a 10 ms task from its
//!   nominal period, which is the figure that matters for real-time work
//!   and the only one here that includes the tick grid's own quantisation.
//!
//! Min and max are reported alongside the mean throughout. A mean on its
//! own says very little about a real-time system.

use core::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::kernel;

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

fn cntpct() -> u64 {
    let v: u64;
    // SAFETY: reading the counter has no side effects. The ISB keeps the
    // read from being speculated ahead of the work being timed.
    unsafe {
        core::arch::asm!("isb", "mrs {}, cntpct_el0", out(reg) v,
                         options(nomem, nostack, preserves_flags))
    };
    v
}

/// Exact for 19.2 MHz: 1e9 / 19.2e6 = 625 / 12.
fn ticks_to_ns(t: u64) -> u64 {
    t.saturating_mul(625) / 12
}

fn print_dec(mut v: u64) {
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

fn w(s: &str) {
    rivet::console::write_str(s);
}

/// One row: label, then min/mean/max in nanoseconds.
fn row(label: &str, min_t: u64, mean_t: u64, max_t: u64) {
    w("  ");
    w(label);
    let pad = 26usize.saturating_sub(label.len());
    for _ in 0..pad {
        w(" ");
    }
    w("min ");
    print_dec(ticks_to_ns(min_t));
    w(" ns   mean ");
    print_dec(ticks_to_ns(mean_t));
    w(" ns   max ");
    print_dec(ticks_to_ns(max_t));
    w(" ns\n");
}

// ── Task-to-task ping-pong ────────────────────────────────────────

/// Whose turn it is. Two tasks, one flag, no allocation.
static TURN_B: AtomicBool = AtomicBool::new(false);
static PONG_DONE: AtomicBool = AtomicBool::new(false);
const PINGPONG: u64 = 2000;

fn pong(_: &'static ()) -> ! {
    let mut n = 0u64;
    while n < PINGPONG {
        if TURN_B.load(Ordering::Acquire) {
            TURN_B.store(false, Ordering::Release);
            n += 1;
        }
        rivet::port::arch::request_reschedule();
    }
    PONG_DONE.store(true, Ordering::Release);
    rivet::preempt::park_forever();
}

// ── Signal wake latency ───────────────────────────────────────────

static SIG: rivet::sync::Signal = rivet::sync::Signal::new();
static SIGNAL_AT: AtomicU64 = AtomicU64::new(0);
static WOKE_AT: AtomicU64 = AtomicU64::new(0);

/// Loops rather than awaiting once: a one-shot task yields exactly one
/// sample, and a single measurement of a latency is not a measurement.
#[rivet::task(priority = 1, stack = 2048)]
async fn signal_waiter() {
    loop {
        SIG.wait().await;
        WOKE_AT.store(cntpct(), Ordering::Release);
        SIG.reset();
    }
}

// ── The benchmark itself ──────────────────────────────────────────

fn bench(_: &'static ()) -> ! {
    w("\n==== rivet rpi3b benchmarks ====\n");
    w("architected timer 19.2 MHz, 1 tick = 52.083 ns\n\n");

    // Let the system settle so start-up transients stay out of the data.
    rivet::preempt::sleep_ms(200);

    // 1. Reschedule round trip, no task change.
    const N: u64 = 20_000;
    let mut min = u64::MAX;
    let mut max = 0u64;
    let mut sum = 0u64;
    for _ in 0..N {
        let t0 = cntpct();
        rivet::port::arch::request_reschedule();
        let d = cntpct() - t0;
        if d < min {
            min = d;
        }
        if d > max {
            max = d;
        }
        sum += d;
    }
    w("context switch machinery\n");
    row("  reschedule round trip", min, sum / N, max);

    // 2. Bare counter read, as the noise floor for everything above.
    let mut fmin = u64::MAX;
    let mut fmax = 0u64;
    let mut fsum = 0u64;
    for _ in 0..N {
        let t0 = cntpct();
        let d = cntpct() - t0;
        if d < fmin {
            fmin = d;
        }
        if d > fmax {
            fmax = d;
        }
        fsum += d;
    }
    row("  measurement overhead", fmin, fsum / N, fmax);

    // 3. Task-to-task switch: hand control over and back, per switch.
    let t0 = cntpct();
    let mut n = 0u64;
    while n < PINGPONG {
        TURN_B.store(true, Ordering::Release);
        while TURN_B.load(Ordering::Acquire) {
            rivet::port::arch::request_reschedule();
        }
        n += 1;
    }
    let total = cntpct() - t0;
    // Two switches per exchange: over to the other task and back.
    let per = total / (PINGPONG * 2);
    w("  task-to-task switch     mean ");
    print_dec(ticks_to_ns(per));
    w(" ns over ");
    print_dec(PINGPONG * 2);
    w(" switches\n\n");

    // 4. Interrupt latency, gathered by the board's tick handler.
    kernel::reset_irq_stats();
    rivet::preempt::sleep_ms(3000);
    let (imin, imax, isum, icnt, tmax, tsum) = kernel::irq_stats();
    w("timer interrupt (");
    print_dec(icnt);
    w(" samples over 3 s)\n");
    if let (Some(ilat), Some(icost)) = (isum.checked_div(icnt), tsum.checked_div(icnt)) {
        row("  hardware to handler", imin, ilat, imax);
        row("  tick handler cost", 0, icost, tmax);
    }
    w("\n");

    // 5. Signal wake: a preemptive task signals, an async task resumes.
    w("wake latency\n");
    let mut smin = u64::MAX;
    let mut smax = 0u64;
    let mut ssum = 0u64;
    let mut samples = 0u64;
    for _ in 0..200 {
        WOKE_AT.store(0, Ordering::Release);
        // Signalled from here, a preemptive task, and observed in an
        // async one, so this is a genuine cross-tier wake rather than a
        // task waking itself.
        SIGNAL_AT.store(cntpct(), Ordering::Release);
        SIG.signal();
        rivet::preempt::sleep_ms(2);
        let woke = WOKE_AT.load(Ordering::Acquire);
        let sent = SIGNAL_AT.load(Ordering::Acquire);
        if woke > sent && sent != 0 {
            let d = woke - sent;
            if d < smin {
                smin = d;
            }
            if d > smax {
                smax = d;
            }
            ssum += d;
            samples += 1;
        }
    }
    if let Some(mean) = ssum.checked_div(samples) {
        row("  Signal to async task", smin, mean, smax);
    } else {
        w("  Signal to async task    no samples\n");
    }
    w("\n");

    // 6. Periodic jitter: the figure that actually matters.
    w("periodic task, 10 ms period, 500 wakeups\n");
    let period_us: u64 = 10_000;
    let mut next = rivet::port::board::now_us() + period_us;
    let mut last = rivet::port::board::now_us();
    let mut jmin = u64::MAX;
    let mut jmax = 0u64;
    let mut jsum = 0u64;
    let mut late = 0u64;
    for i in 0..520u64 {
        rivet::preempt::sleep_until(next);
        let now = rivet::port::board::now_us();
        let gap = now - last;
        last = now;
        next += period_us;
        if i < 20 {
            continue; // discard the grid alignment transient
        }
        let err = gap.abs_diff(period_us);
        if err < jmin {
            jmin = err;
        }
        if err > jmax {
            jmax = err;
        }
        jsum += err;
        if err > 500 {
            late += 1;
        }
    }
    w("  deviation from nominal  min ");
    print_dec(jmin);
    w(" us   mean ");
    print_dec(jsum / 500);
    w(" us   max ");
    print_dec(jmax);
    w(" us\n  wakeups off by >0.5 ms  ");
    print_dec(late);
    w(" of 500\n");

    w("\nBENCH_OK\n");
    rivet::exit_success();
}

#[rivet::main]
fn main() -> ! {
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = pong, arg = ());
    let _ = rivet::spawn_ptask!(stack = 8192, priority = 1, entry = bench, arg = ());
    rivet::run();
}
