#![no_std]
#![no_main]
//! The rivet kernel running on a Raspberry Pi 3B.
//!
//! Proves the AArch64 port end to end: the tick fires, the scheduler
//! runs, and two same-priority preemptive tasks genuinely interleave
//! rather than one running to completion before the other starts.
//!
//! Boot order matters here and is the one thing this file does that the
//! other boards' demos do not. The kernel cannot run until the MMU is on,
//! because its atomics abort against Device memory, so `rust_main` drops
//! to EL1 and installs the identity map *before* handing control to
//! `rivet_main`. Everything after that point is ordinary rivet.

use core::sync::atomic::{AtomicU32, Ordering};

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::{drop_to_el1, mmu};

static A_COUNT: AtomicU32 = AtomicU32::new(0);
static B_COUNT: AtomicU32 = AtomicU32::new(0);

/// Entry from the board's boot code, still at EL2 with no translation.
///
/// Not `#[rivet::main]`: that macro generates `rivet_main`, which is what
/// this calls once the machine is in a state the kernel can survive.
#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack.
    unsafe { drop_to_el1() };
    // SAFETY: called once, at EL1, with translation off. Nothing before
    // this point may use an atomic read-modify-write.
    unsafe { mmu::enable_el1() };

    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

fn worker_a(_: &'static ()) -> ! {
    loop {
        A_COUNT.fetch_add(1, Ordering::Relaxed);
        rivet::preempt::sleep_ms(10);
    }
}

fn worker_b(_: &'static ()) -> ! {
    loop {
        B_COUNT.fetch_add(1, Ordering::Relaxed);
        rivet::preempt::sleep_ms(10);
    }
}

fn checker(_: &'static ()) -> ! {
    // Let the workers run for a while against a clock that is itself
    // being tested, so a dead tick shows up as both counters at zero
    // rather than as a hang.
    let start = rivet::port::board::now_us();
    rivet::preempt::sleep_ms(500);
    let elapsed = rivet::port::board::now_us() - start;

    let a = A_COUNT.load(Ordering::Relaxed);
    let b = B_COUNT.load(Ordering::Relaxed);

    rivet::console::write_str("elapsed_us=");
    print_dec(elapsed as usize);
    rivet::console::write_str(" a=");
    print_dec(a as usize);
    rivet::console::write_str(" b=");
    print_dec(b as usize);
    rivet::console::write_str("\n");

    // The sleep should have taken roughly its nominal time. A wildly
    // wrong figure means the tick rate or the clock is misprogrammed,
    // which is worth distinguishing from the scheduler not working.
    if !(400_000..=700_000).contains(&elapsed) {
        rivet::console::write_str("CLOCK_FAIL\n");
        rivet::exit_failure(1);
    }
    // Both tasks having advanced is the actual context-switch evidence:
    // neither could have run without the other being suspended and
    // resumed around it.
    if a < 10 || b < 10 {
        rivet::console::write_str("SCHED_FAIL\n");
        rivet::exit_failure(2);
    }

    rivet::console::write_str("KERNEL_DEMO_OK\n");
    rivet::exit_success();
}

fn print_dec(mut v: usize) {
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

#[rivet::main]
fn main() -> ! {
    rivet::console::write_str("\nRivet on Raspberry Pi 3B\n");
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = worker_a, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = worker_b, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 2, entry = checker, arg = ());
    rivet::run();
}
