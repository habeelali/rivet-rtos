#![no_std]
#![no_main]
//! Emits a live PulseTrace stream while doing real scheduling work.
//!
//! With the `trace` feature on, the kernel emits frames from the
//! scheduler, the fault path and the IRQ path by itself; nothing here
//! calls the encoder directly. The job of this binary is to give it
//! something worth tracing, and to report from the outside how much came
//! out, so a stream that is silently empty is distinguishable from one
//! that is working.
//!
//! Frames go to their own ring in the shared window rather than the
//! console. The wire format is framed binary and a log line in the middle
//! of it corrupts a frame, so the two cannot share a transport. Drain it
//! from the Linux side with:
//!
//! ```text
//! sudo rivet-amp trace /tmp/rivet.ptrace
//! ```
//!
//! The console still says what is happening in text, which is what makes
//! the binary stream checkable without a decoder present.

use core::sync::atomic::{AtomicU32, Ordering};

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::shmem;

static SWITCHES: AtomicU32 = AtomicU32::new(0);

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack. Brings up the
    // shared rings, which the trace transport needs before any task can
    // emit a frame.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    rivet_bsp_rpi3b::publish_identity!();
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

fn print_dec(mut v: u64) {
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

/// Two tasks at the same priority, ping-ponging, so the scheduler has
/// context switches to describe rather than one task running unopposed.
fn churn_a(_: &'static ()) -> ! {
    loop {
        SWITCHES.fetch_add(1, Ordering::Relaxed);
        rivet::preempt::sleep_ms(5);
    }
}

fn churn_b(_: &'static ()) -> ! {
    loop {
        SWITCHES.fetch_add(1, Ordering::Relaxed);
        rivet::preempt::sleep_ms(7);
    }
}

fn reporter(_: &'static ()) -> ! {
    rivet::console::write_str("\n==== rivet rpi3b trace ====\n");
    rivet::console::write_str("trace ring at ");
    print_dec(shmem::TRACE.pending());
    rivet::console::write_str(" bytes pending at start\n");

    let mut last = 0u64;
    for round in 1..=10u32 {
        rivet::preempt::sleep_ms(1000);
        let pending = shmem::TRACE.pending();
        rivet::console::write_str("t=");
        print_dec(round as u64);
        rivet::console::write_str("s switches=");
        print_dec(SWITCHES.load(Ordering::Relaxed) as u64);
        rivet::console::write_str(" trace_bytes=");
        print_dec(pending);
        rivet::console::write_str("\n");
        last = pending;
    }

    if last == 0 {
        // An empty stream means one of two very different things, and
        // reporting them the same way turns a configuration choice into
        // a spurious failure.
        if rivet_bsp_rpi3b::TRACE_ENABLED {
            rivet::console::write_str("\nTRACE_DEMO_FAIL: tracing is on but no frames arrived\n");
            rivet::exit_failure(1);
        }
        rivet::console::write_str("\nTRACE_DEMO_OK (skipped: built without --features trace)\n");
        rivet::exit_success();
    }
    rivet::console::write_str("\nTRACE_DEMO_OK\n");
    rivet::exit_success();
}

#[rivet::main]
fn main() -> ! {
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = churn_a, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = churn_b, arg = ());
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 2, entry = reporter, arg = ());
    rivet::run();
}
