#![no_std]
#![no_main]
//! Where does a tick's time actually go, and why does it grow under load?
//!
//! `rt_bench` reports tick handler cost as one number, and that number has
//! an awkward shape: 22 samples over a microsecond out of 30000 with Linux
//! idle, against 9168 with Linux saturating its three cores. A step change
//! like that says the handler depends on something the other cores
//! contend for, and the aggregate cannot say what.
//!
//! This times each stage separately, plus a control:
//!
//! - **bookkeeping** — the handler's own latency and interval statistics.
//!   Touches nothing but its module's statics.
//! - **watchdog** — `rivet::watchdog::on_tick`.
//! - **timers** — `rivet::timer::poll_timers`, which walks the timer wheel.
//! - **control** — eight read-modify-writes against private statics, doing
//!   no useful work at all.
//!
//! The control is the point of the exercise. It touches only memory in
//! rivet's reserved region, which Linux cannot map, let alone write. It
//! shares no cache line with anything Linux owns and generates no
//! coherency traffic with the other cluster. If it still slows down under
//! load, then the cause is not sharing, and no amount of removing shared
//! accesses from the tick path will help.
//!
//! Build with `--features tick-phases`. The instrumentation adds counter
//! reads to the tick path, so absolute costs here run higher than
//! `rt_bench` reports. Compare the columns, not the rows.

use rivet_arch_aarch64 as _;
// Everything that reads the per-stage counters is behind the feature, so
// without it this file is a stub that says so.
#[cfg(feature = "tick-phases")]
use rivet_bsp_rpi3b::kernel;

fn w(s: &str) {
    rivet::console::write_str(s);
}

#[cfg(feature = "tick-phases")]
fn dec(mut v: u64) {
    let mut buf = [0u8; 24];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    w(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

#[cfg(feature = "tick-phases")]
fn pad(label: &str, width: usize) {
    w(label);
    for _ in 0..width.saturating_sub(label.len()) {
        w(" ");
    }
}

#[cfg(feature = "tick-phases")]
fn ns(t: u64) -> u64 {
    t.saturating_mul(625) / 12
}

fn report(_: &'static ()) -> ! {
    w("\n==== tick handler anatomy ====\n");

    #[cfg(not(feature = "tick-phases"))]
    {
        w("built without --features tick-phases; nothing to report\n");
        w("TICK_ANATOMY_SKIPPED\n");
        rivet::exit_success();
    }

    #[cfg(feature = "tick-phases")]
    {
        rivet::preempt::sleep_ms(500);
        kernel::reset_irq_stats();
        rivet::preempt::sleep_ms(3000);

        let k = kernel::irq_stats();
        let p = kernel::tick_phase_stats();
        let n = k.count.max(1);

        w("ticks observed: ");
        dec(k.count);
        w("\n\nstage                     mean      max   >1us\n");
        for (label, (max, sum, over)) in [
            ("bookkeeping (own statics)", p[0]),
            ("watchdog", p[1]),
            ("timer wheel", p[2]),
            ("control (private RMW)", p[3]),
        ] {
            w("  ");
            pad(label, 26);
            let mean = ns(sum / n);
            for _ in 0..(6usize.saturating_sub(count_digits(mean))) {
                w(" ");
            }
            dec(mean);
            w("  ");
            let mx = ns(max);
            for _ in 0..(7usize.saturating_sub(count_digits(mx))) {
                w(" ");
            }
            dec(mx);
            w("  ");
            dec(over);
            w("\n");
        }
        w("\ntotal handler cost: mean ");
        dec(ns(k.cost_sum / n));
        w(" max ");
        dec(ns(k.cost_max));
        w(" ns, >1us=");
        dec(k.cost_over);
        w("\ninterrupt latency:  mean ");
        dec(ns(k.lat_sum / n));
        w(" max ");
        dec(ns(k.lat_max));
        w(" ns, >1us=");
        dec(k.lat_over);
        w("\n\nTICK_ANATOMY_OK\n");
        rivet::exit_success();
    }
}

#[cfg(feature = "tick-phases")]
fn count_digits(mut v: u64) -> usize {
    let mut n = 1;
    while v >= 10 {
        v /= 10;
        n += 1;
    }
    n
}

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    rivet_bsp_rpi3b::publish_identity!();
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]` below.
    unsafe { rivet_main() }
}

/// A few sleepers, so the timer wheel has entries to walk rather than
/// being measured empty.
fn sleeper(_: &'static ()) -> ! {
    loop {
        rivet::preempt::sleep_ms(3);
    }
}

#[rivet::main]
fn main() -> ! {
    for _ in 0..4 {
        let _ = rivet::spawn_ptask!(stack = 2048, priority = 1, entry = sleeper, arg = ());
    }
    let _ = rivet::spawn_ptask!(stack = 8192, priority = 2, entry = report, arg = ());
    rivet::run();
}
