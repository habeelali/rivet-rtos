#![no_std]
#![no_main]
//! Exercises the BCM2837 peripheral drivers.
//!
//! How much each check proves depends on what the hardware can be made
//! to talk to itself, which varies a lot between these three:
//!
//! - **PL011** has a real internal loopback bit, so a byte can be sent
//!   and received with nothing attached. This is a complete test.
//! - **GPIO** needs no wire either, because `GPLEV` reports the pad's
//!   actual level rather than the last value written. Driving a pin and
//!   reading it back covers the whole path down to the pin. A second
//!   pin, jumpered, additionally proves one pin can drive another.
//! - **SPI0** has no loopback bit. Without a jumper between MOSI and
//!   MISO the transfer still exercises the clock, chip select, FIFO and
//!   completion handshake, but the received bytes are whatever a
//!   floating input settles to. Reported as two separate outcomes rather
//!   than pretending a float is a pass.
//! - **I2C** has no loopback and a bare Pi has nothing on the bus, so
//!   the test is a scan. Every address NAKing is the expected result and
//!   is itself meaningful: it proves the controller enabled, the clock
//!   ran, transfers started and completed, and the error path reports
//!   instead of hanging.
//!
//! Optional jumpers, if you want the stronger versions:
//!
//! ```text
//!   GPIO23 (pin 16) <-> GPIO24 (pin 18)   cross-pin GPIO
//!   MOSI   (pin 19) <-> MISO   (pin 21)   real SPI loopback
//! ```

use rivet_arch_aarch64 as _;
use rivet_bsp_rpi3b::{gpio, i2c, spi, Pl011};

const UART_CLK_HZ: u32 = 48_000_000;
const BAUD: u32 = 115_200;

/// Jumper candidates. Chosen because nothing else on the board uses them.
const GPIO_OUT: u8 = 23;
const GPIO_IN: u8 = 24;

#[no_mangle]
pub extern "C" fn rust_main(_dtb: u64) -> ! {
    // SAFETY: called once, from EL2, on the boot stack. Does the right
    // thing whether this image owns the board or shares it.
    unsafe { rivet_bsp_rpi3b::board_bringup() };
    extern "C" {
        fn rivet_main() -> !;
    }
    // SAFETY: generated by `#[rivet::main]`.
    unsafe { rivet_main() }
}

/// Whether this is QEMU rather than real silicon: the architected timer
/// runs at 62.5 MHz there and 19.2 MHz here.
fn emulated() -> bool {
    let f: u64;
    // SAFETY: reading CNTFRQ_EL0 has no side effects.
    unsafe {
        core::arch::asm!("mrs {}, cntfrq_el0", out(reg) f,
                         options(nomem, nostack, preserves_flags))
    };
    f != 19_200_000
}

fn line(s: &str) {
    rivet::console::write_str(s);
    rivet::console::write_str("\n");
}

fn print_dec(mut v: usize) {
    let mut buf = [0u8; 20];
    let mut i = buf.len();
    loop {
        i -= 1;
        buf[i] = b'0' + (v % 10) as u8;
        v /= 10;
        if v == 0 {
            break;
        }
    }
    // SAFETY: every byte written is an ASCII digit.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf[i..]) });
}

fn print_hex8(v: u8) {
    const D: &[u8; 16] = b"0123456789abcdef";
    let buf = [D[(v >> 4) as usize], D[(v & 0xf) as usize]];
    // SAFETY: both bytes are ASCII hex digits.
    rivet::console::write_str(unsafe { core::str::from_utf8_unchecked(&buf) });
}

// ── PL011 internal loopback ───────────────────────────────────────

fn test_pl011() -> bool {
    if rivet_bsp_rpi3b::AMP {
        // The UART is the other operating system's console. Driving it
        // into loopback would cut its output mid-line and hand it back
        // reconfigured.
        line("  skip PL011 loopback: the UART belongs to Linux in this build");
        return true;
    }
    if emulated() {
        // QEMU's PL011 ignores the loopback bit, so the pattern goes out
        // of the real serial port instead of coming back, corrupting the
        // console and failing for a reason that says nothing about the
        // driver.
        line("  skip PL011 loopback: QEMU does not model the LBE bit");
        return true;
    }
    let uart = Pl011;
    // Draining first matters: the loopback bit is about to redirect the
    // transmitter, and anything still in the FIFO would vanish.
    // SAFETY: this core owns the UART.
    unsafe { uart.flush() };

    let pattern = [0x5Au8, 0xA5, 0x00, 0xFF, 0x42];
    let mut ok = true;
    // SAFETY: loopback ties TX to RX inside the block; nothing reaches
    // the pins while it is on.
    unsafe {
        uart.set_loopback(true);
        // Drain anything the receiver had queued before the switch.
        while uart.try_read().is_some() {}

        for &b in &pattern {
            uart.put_byte(b);
            uart.flush();
            // The received byte appears a moment after the transmitter
            // reports idle, so give the receiver a bounded chance.
            let mut got = None;
            for _ in 0..10_000 {
                if let Some(r) = uart.try_read() {
                    got = Some(r);
                    break;
                }
            }
            if got != Some(b) {
                ok = false;
            }
        }
        uart.set_loopback(false);
        uart.init(UART_CLK_HZ, BAUD);
    }

    if ok {
        line("  ok   PL011 internal loopback returned all 5 bytes");
    } else {
        line("  FAIL PL011 loopback mismatch");
    }
    ok
}

// ── GPIO ──────────────────────────────────────────────────────────

fn test_gpio() -> bool {
    // SAFETY: nothing else is using these pins on a bare board.
    let mut out = unsafe { gpio::Pin::output(GPIO_OUT) };
    let inp = unsafe { gpio::Pin::input(GPIO_IN) };
    // A pull-down so an unjumpered input reads a defined low rather than
    // floating, which is what makes the "no jumper" case detectable
    // instead of random.
    // SAFETY: we own the pin.
    unsafe { gpio::set_pull(GPIO_IN, gpio::pull::DOWN) };

    out.set_high();
    rivet_bsp_rpi3b::delay(2000);
    let self_high = out.level();
    let cross_high = inp.is_high();

    out.set_low();
    rivet_bsp_rpi3b::delay(2000);
    let self_low = !out.level();
    let cross_low = !inp.is_high();

    let self_ok = self_high && self_low;
    if self_ok {
        line("  ok   GPIO output read back its own driven level");
    } else {
        line("  FAIL GPIO output did not read back");
    }

    if cross_high && cross_low {
        line("  ok   GPIO23 drove GPIO24 (jumper present)");
    } else {
        line("  note GPIO24 did not follow GPIO23: no jumper, as expected bare");
    }
    self_ok
}

// ── SPI0 ──────────────────────────────────────────────────────────

fn test_spi() -> bool {
    let s = spi::Spi0;
    // 250 MHz / 256 is just under 1 MHz, slow enough that a jumper wire
    // is not the limiting factor.
    // SAFETY: this core owns GPIO 7-11 and SPI0.
    unsafe { s.init(256) };

    let pattern = [0xDEu8, 0xAD, 0xBE, 0xEF];
    let mut buf = pattern;
    // SAFETY: the controller was just initialised.
    if unsafe { s.transfer(&mut buf) }.is_err() {
        line("  note SPI0 transfer timed out: controller absent or not modelled");
        return true;
    }

    if buf == pattern {
        line("  ok   SPI0 loopback returned the pattern (MOSI-MISO jumpered)");
        true
    } else {
        rivet::console::write_str("  note SPI0 transfer completed, read back ");
        for b in buf {
            print_hex8(b);
        }
        rivet::console::write_str(" (no jumper: clock, CS and FIFO exercised,\n");
        line("       data not looped back)");
        // The transfer completing at all is the part that can fail
        // outright; a floating read is not a driver fault.
        true
    }
}

// ── I2C ───────────────────────────────────────────────────────────

fn test_i2c() -> bool {
    let bus = i2c::I2c1;
    // 150 MHz / 1500 = 100 kHz, the standard rate.
    // SAFETY: this core owns GPIO 2/3 and BSC1.
    unsafe { bus.init(1500) };

    let mut found = 0;
    let mut errors = 0;
    for addr in 0x08u8..0x78 {
        // SAFETY: the controller was just initialised.
        if unsafe { bus.probe(addr) } {
            found += 1;
            // Only name the first few: if the count runs away, the list
            // is noise and the count is the interesting part.
            if found <= 8 {
                rivet::console::write_str("  ..   device responded at 0x");
                print_hex8(addr);
                rivet::console::write_str("\n");
            }
        } else {
            errors += 1;
        }
    }

    // More than a handful of replies on one bus is not a bus full of
    // devices, it is a driver reporting success it did not earn. Saying
    // so beats printing a list that looks like a discovery.
    if found > 8 {
        rivet::console::write_str("  FAIL I2C1 scan: ");
        print_dec(found);
        line(" of 112 addresses replied, which is not plausible");
        return false;
    }

    // Every address NAKing is the expected outcome on a bare board, and
    // it still proves the controller ran and reported rather than hung.
    if errors > 0 {
        rivet::console::write_str("  ok   I2C1 scanned 112 addresses, ");
        if found == 0 {
            line("all NAKed (nothing on the bus)");
        } else {
            line("some responded");
        }
        true
    } else {
        line("  FAIL I2C1 scan produced no result at all");
        false
    }
}

fn runner(_: &'static ()) -> ! {
    line("\n==== rivet rpi3b peripherals ====");
    let mut all = true;
    all &= test_pl011();
    all &= test_gpio();
    all &= test_spi();
    all &= test_i2c();

    rivet::console::write_str("\n");
    if all {
        line("PERIPH_TEST_OK");
        rivet::exit_success();
    }
    line("PERIPH_TEST_FAIL");
    rivet::exit_failure(1);
}

#[rivet::main]
fn main() -> ! {
    let _ = rivet::spawn_ptask!(stack = 4096, priority = 1, entry = runner, arg = ());
    rivet::run();
}
